/**
 * 绑定认领请求 DTO - ClaimBindingDto
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 用途说明
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * 本 DTO 用于商户认领绑定接口（POST /bindings/claim）的请求数据验证。
 *
 * 当商户通过管理后台点击绑定链接确认绑定时，需要提交此 DTO。
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 完整绑定流程
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 *  1. [经销商] 商户后台 → 经销商管理 → 生成绑定二维码
 *     └─→ 二维码包含 JWT token
 *
 *  2. [商户管理员] 扫描二维码 → 前端调用 GET /bindings/verify/:token
 *     └─→ 验证二维码有效性，查看经销商信息
 *
 *  3. [商户管理员] 点击"确认绑定" → 前端调用 POST /bindings/claim
 *     └─→ 提交 { token: "..." } → 本 DTO 验证
 *
 *  4. [系统] 创建 Binding + CRM 线索 + 发送邮件
 *     └─→ 返回绑定记录
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * Token 来源
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 * - 由 DistributorsService.generateQr() 生成
 * - 存储于 DistributorQrCode.token
 * - 是 JWT 格式，包含 distributorId, tenantId, bindType 等信息
 * - 有过期时间（默认 7 天）
 * - 可被经销商撤销（revokedAt）
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 验证规则
 * ═══════════════════════════════════════════════════════════════════════════════
 *
 *   字段   │ 类型     │ 验证规则          │ 说明
 *   ───────┼──────────┼───────────────────┼──────────────────────────
 *   token  │ string   │ @IsString()       │ JWT 格式的绑定令牌
 *          │          │ (必填)            │ 不能为空
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 */

import { IsString } from 'class-validator';

/**
 * 绑定认领请求 DTO - ClaimBindingDto
 *
 * 用于商户在管理后台确认与经销商绑定关系时提交的数据。
 * 包含必要的绑定令牌，用于验证和确认绑定操作。
 *
 * @see BindingsController.claimMerchant() 使用此 DTO
 * @see BindingsService.claimMerchant() 处理业务逻辑
 */
export class ClaimBindingDto {
  /**
   * 绑定令牌 - token
   *
   * ═══════════════════════════════════════════════════════════════════════════════
   *
   * 这是经销商分发的二维码/链接中包含的唯一标识符（JWT 格式）。
   *
   * JWT Payload 结构：
   * {
   *   distributorId: string,   // 发行二维码的经销商ID
   *   tenantId: string,        // 租户ID（用于校验）
   *   bindType: 'MERCHANT',     // 绑定类型
   *   purpose: 'bind',          // 用途标识
   *   jti: string,             // 唯一ID，防重放
   *   exp: number,              // 过期时间戳
   * }
   *
   * ═══════════════════════════════════════════════════════════════════════════════
   * 验证方式
   * ═══════════════════════════════════════════════════════════════════════════════
   *
   * 服务端会进行四层验证：
   * 1. 查询 DistributorQrCode.token = token（数据库存在性）
   * 2. 检查 qr.revokedAt === null（未被撤销）
   * 3. 检查 qr.expiresAt > now()（未过期）
   * 4. jwt.verify(token, { secret: BIND_TOKEN_SECRET })（JWT 签名）
   *
   * ═══════════════════════════════════════════════════════════════════════════════
   * 使用示例
   * ═══════════════════════════════════════════════════════════════════════════════
   *
   * {
   *   "token": "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJkaXN0cmlidXRvcklkIjoiZGlzdF94eHg..."
   * }
   *
   * @example "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9..."
   */
  @IsString()
  token!: string;
}
